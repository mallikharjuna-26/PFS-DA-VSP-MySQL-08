 SELECT D.DEPARTMENT_NAME,COUNT(E.EMP_ID)AS TOTAL_EMPLOYEES
 FROM DEPARTMENTS D
 LEFT JOIN EMPLOYEES E
 ON D.DEPARTMENT_ID=E.DEPARTMENT_ID
 GROUP BY D.DEPARTMENT_NAME
 HAVING TOTAL_EMPLOYEES>1
 ORDER BY TOTAL_EMPLOYEES DESC;
 
 
