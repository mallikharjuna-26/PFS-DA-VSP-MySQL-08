USE DA8;
CREATE TABLE PRODUCTS(
     PID INT PRIMARY KEY,
     NAME VARCHAR(20),
     PRICE DECIMAL(10,2),
     QTY INT,
     TOTALAMOUNT DECIMAL(10,2)GENERATED ALWAYS AS(PRICE*QTY)STORED
     );
     
